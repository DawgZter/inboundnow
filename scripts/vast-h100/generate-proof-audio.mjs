#!/usr/bin/env node
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { encodePcm16Wav } from "../../packages/voice-input/index.mjs";

const outputPath = process.env.PROOF_AUDIO_PATH || "artifacts/asr-smoke/global-payroll.wav";
const baseUrl = process.env.TTS_BASE_URL || "http://127.0.0.1:4331";
const text = process.env.PROOF_AUDIO_TEXT || "How does Remote help with global payroll?";
const model = process.env.TTS_MODEL || "MisoLabs/MisoTTS";
const voice = process.env.TTS_VOICE || "miso-one-lora-dev";
const style = process.env.TTS_VOICE_STYLE || "expressive";
const loraAdapter = process.env.MISO_LORA_ADAPTER || "artifacts/miso-lora/adapters/miso-one-lora-dev";

function endpoint(pathname) {
  return new URL(pathname, baseUrl.endsWith("/") ? baseUrl : baseUrl + "/");
}

async function readNdjson(response) {
  const reader = response.body.getReader();
  const decoder = new TextDecoder();
  let buffered = "";
  const events = [];
  while (true) {
    const { value, done } = await reader.read();
    if (done) break;
    buffered += decoder.decode(value, { stream: true });
    let index;
    while ((index = buffered.indexOf("\n")) >= 0) {
      const line = buffered.slice(0, index).trim();
      buffered = buffered.slice(index + 1);
      if (line) events.push(JSON.parse(line));
    }
  }
  const tail = buffered.trim();
  if (tail) events.push(JSON.parse(tail));
  return events;
}

const healthResponse = await fetch(endpoint("health"));
assert.equal(healthResponse.ok, true, "Miso proof-audio generator requires a healthy local TTS endpoint");
const health = await healthResponse.json();
assert.equal(health.provider, "local-miso-one");
assert.equal(health.localOnly, true);

const response = await fetch(endpoint("v1/tts/stream"), {
  method: "POST",
  headers: { "content-type": "application/json" },
  body: JSON.stringify({
    text,
    model,
    voice,
    style,
    loraAdapter,
    requestId: "h100_proof_audio",
  }),
});

if (!response.ok) {
  const body = await response.text();
  throw new Error("Miso proof-audio generation failed with HTTP " + response.status + ": " + body.slice(0, 500));
}

const events = await readNdjson(response);
const chunks = events.filter((event) => event.type === "chunk" && event.audio).map((event) => Buffer.from(event.audio, "base64"));
assert.ok(chunks.length > 0, "proof-audio generation requires at least one audio chunk");
const sampleRate = Number(events.find((event) => event.sampleRate)?.sampleRate || 24000);
const pcm = Buffer.concat(chunks);
const wav = encodePcm16Wav(pcm, { sampleRate, channels: 1 });
await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, wav);

const result = {
  ok: true,
  proof: "h100-local-miso-proof-audio-fixture",
  boundary: "Generated by the local Miso One/MisoTTS endpoint for automated media-fixture proof; this is not manual human microphone proof.",
  outputPath: resolve(outputPath),
  text,
  baseUrl,
  model,
  voice,
  style,
  sampleRate,
  channels: 1,
  pcmBytes: pcm.length,
  wavBytes: wav.length,
  audioSha256: createHash("sha256").update(wav).digest("hex"),
  health: {
    provider: health.provider,
    model: health.model,
    localOnly: health.localOnly,
    device: health.device,
    gpuName: health.gpuName,
    loraRuntimeSupported: health.loraRuntimeSupported,
  },
  eventCount: events.length,
  chunkCount: chunks.length,
};

const resultPath = join(dirname(outputPath), "proof-audio-result.json");
await writeFile(resultPath, JSON.stringify(result, null, 2));
console.log(JSON.stringify({ ...result, resultPath: resolve(resultPath) }, null, 2));
